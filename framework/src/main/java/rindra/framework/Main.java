package rindra.framework;

/**
 * Point d'entrée de démonstration du framework.
 * Cette classe sert simplement à vérifier qu'un projet Java simple peut
 * être démarré dans le contexte du framework.
 */
public class Main {
    public static void main(String[] args) {
        // Exemple de lancement : un projet Java standard peut afficher
        // un message de bienvenue avant l'exécution plus complexe du serveur.
        System.out.println("Hello world!");
    }
}